# Initialize a vaar balance . perform  operations using  shorthand operations like +=,-=,*=,/= and print bal after each op.
bal = float(input("Enter balance: "))
bal = 1000
bal += 500
print("Balance ADDED: ", bal)
bal -= 200
print("Balance SUBTRACTED: ", bal)
bal *= 2
print("Balance MULTIPLIED: ", bal)
bal /= 4
print("Balance DIVIDED: ", bal)
